from __future__ import annotations

import argparse
import concurrent.futures
import os
from pathlib import Path

from tools.eval.run_one_step_eval import (
    EvalSummary,
    Reporter,
    _discrete_mismatch_total,
    create_one_step_eval_runtime,
    evaluate_dataset,
)
from tools.eval.run_one_step_eval import _strict_discrete_mismatch_total
from tools.eval.validation_profile import get_validation_profile, validation_profile_names
from tools.slippi.slpz import resolve_replay_path
from tools.slippi.suite_io import load_suite, repo_root


class _CaptureReporter:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def print(self, *args) -> None:
        self.lines.append(" ".join(str(a) for a in args))

    def close(self) -> None:
        return None


def _resolve_worker_count(requested: int, task_count: int) -> int:
    if int(requested) > 0:
        return max(1, int(requested))
    return max(1, min(8, int(os.cpu_count() or 1), int(task_count) if task_count else 1))


def _display_path(path: Path, *, root: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(root))
    except ValueError:
        return str(resolved)


def _evaluate_dataset_task(task: dict) -> dict:
    from tools.slippi.make_dataset_from_slp import build_dataset_from_slp

    dataset_label = Path(str(task["dataset_label"]))
    dataset = build_dataset_from_slp(
        slp_path=str(task["slp_path"]),
        ports=[int(p) for p in task["ports"]],
        ucf_enabled=bool(task["ucf_enabled"]),
        ucf_cardinals_1_0_enabled=bool(task["ucf_cardinals_1_0_enabled"]),
    )
    records = int(dataset.header["num_records"])
    num_players = int(dataset.header["num_players"])
    runtime = create_one_step_eval_runtime(
        batch_size=max(1, min(int(task["chunk"]), max(1, records))),
        num_players=int(num_players),
        ucf_enabled=bool(task["ucf_enabled"]),
        ucf_cardinals_1_0_enabled=bool(task["ucf_cardinals_1_0_enabled"]),
    )
    capture = _CaptureReporter()
    try:
        summary = evaluate_dataset(
            dataset_path=dataset_label,
            dataset=dataset,
            chunk=int(task["chunk"]),
            runtime=runtime,
            profile=str(task["profile"]),
            ucf_enabled=bool(task["ucf_enabled"]),
            ucf_cardinals_1_0_enabled=bool(task["ucf_cardinals_1_0_enabled"]),
            reporter=capture,  # type: ignore[arg-type]
            print_profile=False,
            debug_mismatch=tuple(task["debug_mismatch"]),
            debug_limit=int(task["debug_limit"]),
            debug_float=tuple(task["debug_float"]),
            debug_float_limit=int(task["debug_float_limit"]),
        )
    finally:
        runtime.close()
    return {"one_step_lines": capture.lines, "one_step_summary": summary}


def _report_header(*, root: Path, suite: str, suite_name: str) -> list[str]:
    # Minimal committed-snapshot header: the metric lines below are the report; regeneration
    # instructions stay generic and suite-derived (no hardcoded character lists).
    return [
        f"# Generated by run_one_step_suite_eval --suite {suite} (overwritten each run).",
        "# Validation input: direct .slp/.slpz replay ingest; no .msl cache is read or written.",
        "# Regenerate data artifacts: uv run python -m tools.extraction.build_data (chars default to the registry)",
    ]


def emit_one_step_suite_report(
    *,
    reporter: Reporter,
    root: Path,
    suite_arg: str,
    suite_name: str,
    replay_paths: list[Path],
    task_results: list[dict],
    validation_profile,
    ucf_enabled: bool | None,
    ucf_cardinals_1_0_enabled: bool | None,
    include_header: bool,
) -> None:
    if include_header:
        for line in _report_header(root=root, suite=suite_arg, suite_name=suite_name):
            reporter.print(line)
        reporter.print()

    reporter.print(
        f"suite: {suite_name}  replays: {len(replay_paths)}  "
        f"ucf_enabled: {ucf_enabled}  ucf_cardinals_1_0_enabled: {ucf_cardinals_1_0_enabled}"
    )
    reporter.print(f"validation.profile: {validation_profile.name}")
    for lane in validation_profile.ignored_lanes:
        reporter.print(f"validation.profile.ignored: {lane.label} reason={lane.reason} exception={lane.exception}")

    suite_mismatches: dict[str, int] | None = None
    suite_strict_mismatches: dict[str, int] | None = None
    suite_ignored_mismatches: dict[str, int] | None = None
    suite_totals = {
        "total_records": 0,
        "total_player_frames": 0,
        "total_state_flags": 0,
        "total_item_slots": 0,
        "float_norm_sum": 0.0,
        "float_norm_count": 0,
    }

    for replay_path, result in zip(replay_paths, task_results, strict=True):
        summary: EvalSummary = result["one_step_summary"]
        reporter.print()
        reporter.print(f"== {_display_path(replay_path, root=root)} ==")
        for line in result["one_step_lines"]:
            reporter.print(line)

        if suite_mismatches is None:
            suite_mismatches = {k: 0 for k in summary.mismatches.keys()}
            suite_strict_mismatches = {k: 0 for k in summary.strict_mismatches.keys()}
            suite_ignored_mismatches = {k: 0 for k in summary.ignored_mismatches.keys()}
        for k, v in summary.mismatches.items():
            suite_mismatches[k] += v
        assert suite_strict_mismatches is not None
        for k, v in summary.strict_mismatches.items():
            suite_strict_mismatches[k] += v
        assert suite_ignored_mismatches is not None
        for k, v in summary.ignored_mismatches.items():
            suite_ignored_mismatches[k] += v
        suite_totals["total_records"] += summary.total_records
        suite_totals["total_player_frames"] += summary.total_player_frames
        suite_totals["total_state_flags"] += summary.total_state_flags
        suite_totals["total_item_slots"] += summary.total_item_slots
        suite_totals["float_norm_sum"] += summary.float_norm_sum
        suite_totals["float_norm_count"] += summary.float_norm_count

    if suite_mismatches is None or suite_strict_mismatches is None or suite_ignored_mismatches is None:
        return

    reporter.print()
    reporter.print("== suite summary ==")
    suite_summary = EvalSummary(
        total_records=suite_totals["total_records"],
        total_player_frames=suite_totals["total_player_frames"],
        total_state_flags=suite_totals["total_state_flags"],
        total_item_slots=suite_totals["total_item_slots"],
        mismatches=suite_mismatches,
        strict_mismatches=suite_strict_mismatches,
        ignored_mismatches=suite_ignored_mismatches,
        profile_name=validation_profile.name,
        float_norm_sum=float(suite_totals["float_norm_sum"]),
        float_norm_count=int(suite_totals["float_norm_count"]),
    )
    mismatches_total, checks_total = _discrete_mismatch_total(suite_summary, profile=validation_profile)
    strict_total, strict_checks = _strict_discrete_mismatch_total(suite_summary)
    reporter.print(f"overall.discrete_mismatch: {mismatches_total} / {checks_total}")
    reporter.print(f"overall.strict_discrete_mismatch: {strict_total} / {strict_checks}")
    reporter.print(f"overall.ignored_discrete_mismatch: {sum(suite_ignored_mismatches.values())}")
    overall_float = (
        suite_summary.float_norm_sum / suite_summary.float_norm_count
        if suite_summary.float_norm_count > 0
        else 0.0
    )
    reporter.print(f"overall.float_norm_mae_p95: {overall_float:.8f}")



def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", required=True, help="Path to suite JSON (e.g. replays/suites/...)")
    ap.add_argument("--chunk", type=int, default=4096)
    ap.add_argument(
        "--profile",
        default="rl1_gameplay",
        choices=validation_profile_names(),
        help="Validation scoring profile. strict scores every compare lane; rl1_gameplay ignores RL1-irrelevant lanes.",
    )
    ap.add_argument("--out", type=Path, default=None, help="optional output path to write the report")
    ap.add_argument(
        "--debug-mismatch",
        default="",
        help="comma-separated discrete fields to print first mismatches for (e.g. 'stocks,is_dead')",
    )
    ap.add_argument(
        "--debug-limit",
        type=int,
        default=10,
        help="max mismatching records to print per dataset per debug field",
    )
    ap.add_argument(
        "--debug-float",
        default="",
        help="comma-separated float fields to print top absolute errors for (e.g. 'speed_ground_x_self,pos_x')",
    )
    ap.add_argument(
        "--debug-float-limit",
        type=int,
        default=10,
        help="max top-error rows to print per dataset per debug float field",
    )
    ap.add_argument(
        "--quiet",
        action="store_true",
        help="Write --out report without echoing the full report to stdout.",
    )
    ap.add_argument(
        "--workers",
        type=int,
        default=0,
        help="Parallel dataset eval workers (0 = auto, capped at 8).",
    )
    args = ap.parse_args()

    root = repo_root()
    validation_profile = get_validation_profile(args.profile)
    suite_path = (root / args.suite).resolve()
    suite = load_suite(suite_path)

    replay_paths = [resolve_replay_path((root / entry.replay).resolve()) for entry in suite.replays]

    reporter = Reporter(args.out, echo=not bool(args.quiet))
    try:
        num_players = len(suite.replays[0].ports) if suite.replays else 2
        if any(len(entry.ports) != num_players for entry in suite.replays):
            raise SystemExit("error: mixed num_players suites are not supported by shared one-step eval runtime")
        tasks = [
            {
                "dataset_label": str(replay_path),
                "slp_path": str(replay_path),
                "ports": [int(p) for p in entry.ports],
                "chunk": int(args.chunk),
                "profile": validation_profile.name,
                "ucf_enabled": bool(suite.ucf_enabled),
                "ucf_cardinals_1_0_enabled": bool(suite.ucf_cardinals_1_0_enabled),
                "debug_mismatch": tuple(s.strip() for s in args.debug_mismatch.split(",") if s.strip() != ""),
                "debug_limit": int(args.debug_limit),
                "debug_float": tuple(s.strip() for s in args.debug_float.split(",") if s.strip() != ""),
                "debug_float_limit": int(args.debug_float_limit),
            }
            for replay_path, entry in zip(replay_paths, suite.replays, strict=True)
        ]
        workers = _resolve_worker_count(int(args.workers), len(tasks))
        if workers == 1 or len(tasks) <= 1:
            task_results = [_evaluate_dataset_task(task) for task in tasks]
        else:
            with concurrent.futures.ProcessPoolExecutor(max_workers=workers) as executor:
                task_results = list(executor.map(_evaluate_dataset_task, tasks))
        emit_one_step_suite_report(
            reporter=reporter,
            root=root,
            suite_arg=args.suite,
            suite_name=suite.name,
            replay_paths=replay_paths,
            task_results=task_results,
            validation_profile=validation_profile,
            ucf_enabled=suite.ucf_enabled,
            ucf_cardinals_1_0_enabled=suite.ucf_cardinals_1_0_enabled,
            include_header=args.out is not None,
        )
    finally:
        reporter.close()


if __name__ == "__main__":
    main()
