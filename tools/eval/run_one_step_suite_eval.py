from __future__ import annotations

import argparse
from pathlib import Path

from tools.eval.run_one_step_eval import EvalSummary, Reporter, _discrete_mismatch_total, evaluate_dataset
from tools.eval.run_one_step_eval import _strict_discrete_mismatch_total
from tools.eval.validation_profile import get_validation_profile, validation_profile_names
from tools.slippi.suite_io import dataset_path_for_suite_replay, load_suite, repo_root


def _report_header(*, root: Path, suite: str, suite_name: str, datasets_dir: str) -> list[str]:
    # This header is a process requirement for committed validation snapshots under
    # `reports/validation/`: it documents how to recover if local, gitignored artifacts are missing
    # or stale. `make validate` overwrites the report file, so we emit this block at runtime.
    return [
        "# NOTE: This report is generated by `make validate OUT=reports/validation/one_step_suite_eval.txt` and is overwritten on each run.",
        "#",
        "# Dataset cache note:",
        "# - If you see a `record_size mismatch` error, the dataset schema changed and your cached datasets are stale.",
        "#   Refresh cached datasets:",
        f"#     uv run python -m tools.slippi.preprocess_suite --suite {suite} --datasets-dir {datasets_dir}",
        "#",
        "# Regenerate gitignored ISO-derived data artifacts (if missing/stale):",
        "# - Moves (data/moves/*.json):",
        "#     uv run python -m tools.extraction.extract_fighter_moves --iso_dir _iso --out_dir data/moves --chars fox,falco",
        "# - Anim tracks (data/anims/{fox,falco}.tracks.bin; SSANIMT1 v2 w/ AOBJ loop flags):",
        "#     uv run python -m tools.extraction.extract_fighter_anims --character fox --out-dir data/anims",
        "#     uv run python -m tools.extraction.extract_fighter_anims --character falco --out-dir data/anims",
        "# - ECB tables (data/ecb/*):",
        "#   Note: ECB outputs depend on which submotions `extract_fighter_anims` includes. If ECB-related grounding changes",
        "#   (e.g. DamageFlyTop landings / knockdown edge behavior) look wrong, rebuild the ECB anim bundle + tables:",
        "#     uv run python -m tools.extraction.extract_fighter_anims --character fox --out-dir data/anims_ecb",
        "#     uv run python -m tools.extraction.extract_fighter_anims --character falco --out-dir data/anims_ecb",
        "#     uv run python -m tools.extraction.extract_ecb_bottom --character fox --anims data/anims_ecb/fox.bin --attrs data/characters/fox.json --out data/ecb/fox_bottom.bin",
        "#     uv run python -m tools.extraction.extract_ecb_bottom --character falco --anims data/anims_ecb/falco.bin --attrs data/characters/falco.json --out data/ecb/falco_bottom.bin",
        "#     uv run python -m tools.extraction.extract_ecb_extents --character fox --anims data/anims_ecb/fox.bin --attrs data/characters/fox.json --out data/ecb/fox_extents.bin",
        "#     uv run python -m tools.extraction.extract_ecb_extents --character falco --anims data/anims_ecb/falco.bin --attrs data/characters/falco.json --out data/ecb/falco_extents.bin",
        "# - Lasers (data/items/lasers.bin):",
        "#     uv run python -m tools.extraction.extract_lasers --iso_dir _iso --out data/items/lasers.bin",
        "# - Character attrs (data/characters/*.json, includes model_scaling):",
        "#     uv run python -m tools.extraction.extract_character_attrs --pl-dir _iso --out-dir data/characters --chars fox,falco",
        "# - Opcode-25 airborne-state timelines (data/airborne_state_events/{fox,falco}.bin):",
        "#     uv run python -m tools.extraction.extract_fighter_airborne_state_events --iso_dir _iso --melee_decomp refs/melee --special_msids_dir data/special_msids --out_dir data/airborne_state_events --chars fox,falco",
        "#   Note: runtime degrades safely when these bins are missing, but transition/grounding parity can differ.",
        "# - Opcode-52 x221C_u16_y timelines (data/state_flags_221c_y/{fox,falco}.bin):",
        "#     uv run python -m tools.extraction.extract_fighter_state_flags_221c_y --iso_dir _iso --melee_decomp refs/melee --special_msids_dir data/special_msids --out_dir data/state_flags_221c_y --chars fox,falco",
        "#   Note: runtime degrades safely when these bins are missing, but state_flags parity/suite totals can differ.",
        "#",
        "# (Optional) One-shot build for stage+chars:",
        "#     uv run python -m tools.extraction.build_data --iso-dir _iso --stage grnla --chars fox,falco",
    ]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", required=True, help="Path to suite JSON (e.g. replays/suites/...)")
    ap.add_argument(
        "--datasets-dir",
        default="datasets",
        help="Directory under repo root that stores preprocessed datasets",
    )
    ap.add_argument("--chunk", type=int, default=4096)
    ap.add_argument(
        "--profile",
        default="rl1_gameplay",
        choices=validation_profile_names(),
        help="Validation scoring profile. strict scores every compare lane; rl1_gameplay ignores RL1-irrelevant lanes.",
    )
    ap.add_argument("--out", type=Path, default=None, help="optional output path to write the report")
    ap.add_argument(
        "--debug-mismatch",
        default="",
        help="comma-separated discrete fields to print first mismatches for (e.g. 'stocks,is_dead')",
    )
    ap.add_argument(
        "--debug-limit",
        type=int,
        default=10,
        help="max mismatching records to print per dataset per debug field",
    )
    ap.add_argument(
        "--debug-float",
        default="",
        help="comma-separated float fields to print top absolute errors for (e.g. 'speed_ground_x_self,pos_x')",
    )
    ap.add_argument(
        "--debug-float-limit",
        type=int,
        default=10,
        help="max top-error rows to print per dataset per debug float field",
    )
    args = ap.parse_args()

    root = repo_root()
    validation_profile = get_validation_profile(args.profile)
    suite_path = (root / args.suite).resolve()
    suite = load_suite(suite_path)

    missing = []
    dataset_paths: list[Path] = []
    for entry in suite.replays:
        ds_path = dataset_path_for_suite_replay(
            suite_name=suite.name,
            replay_rel_path=entry.replay,
            datasets_dir=args.datasets_dir,
        )
        if not ds_path.exists():
            missing.append(str(ds_path.relative_to(root)))
        else:
            dataset_paths.append(ds_path)

    if missing:
        print(f"Missing {len(missing)} preprocessed dataset files for suite {suite.name}:")
        for p in missing:
            print(f"  {p}")
        print("Run preprocessing first:")
        print(f"  uv run python -m tools.slippi.preprocess_suite --suite {args.suite} --datasets-dir {args.datasets_dir}")
        raise SystemExit(2)

    reporter = Reporter(args.out)
    try:
        if args.out is not None:
            for line in _report_header(
                root=root, suite=args.suite, suite_name=suite.name, datasets_dir=args.datasets_dir
            ):
                reporter.print(line)
            reporter.print()

        reporter.print(
            f"suite: {suite.name}  datasets: {len(dataset_paths)}  "
            f"ucf_enabled: {suite.ucf_enabled}  ucf_cardinals_1_0_enabled: {suite.ucf_cardinals_1_0_enabled}"
        )
        reporter.print(f"validation.profile: {validation_profile.name}")
        for lane in validation_profile.ignored_lanes:
            reporter.print(f"validation.profile.ignored: {lane.label} reason={lane.reason} exception={lane.exception}")
        suite_mismatches: dict[str, int] | None = None
        suite_strict_mismatches: dict[str, int] | None = None
        suite_ignored_mismatches: dict[str, int] | None = None
        suite_totals = {
            "total_records": 0,
            "total_player_frames": 0,
            "total_state_flags": 0,
            "total_item_slots": 0,
            "float_norm_sum": 0.0,
            "float_norm_count": 0,
        }

        for ds in dataset_paths:
            reporter.print()
            reporter.print(f"== {ds.relative_to(root)} ==")
            summary = evaluate_dataset(
                dataset_path=ds,
                chunk=args.chunk,
                profile=validation_profile,
                ucf_enabled=suite.ucf_enabled,
                ucf_cardinals_1_0_enabled=suite.ucf_cardinals_1_0_enabled,
                reporter=reporter,
                print_profile=False,
                debug_mismatch=tuple(
                    s.strip() for s in args.debug_mismatch.split(",") if s.strip() != ""
                ),
                debug_limit=int(args.debug_limit),
                debug_float=tuple(
                    s.strip() for s in args.debug_float.split(",") if s.strip() != ""
                ),
                debug_float_limit=int(args.debug_float_limit),
            )

            if suite_mismatches is None:
                suite_mismatches = {k: 0 for k in summary.mismatches.keys()}
                suite_strict_mismatches = {k: 0 for k in summary.strict_mismatches.keys()}
                suite_ignored_mismatches = {k: 0 for k in summary.ignored_mismatches.keys()}
            for k, v in summary.mismatches.items():
                suite_mismatches[k] += v
            assert suite_strict_mismatches is not None
            for k, v in summary.strict_mismatches.items():
                suite_strict_mismatches[k] += v
            assert suite_ignored_mismatches is not None
            for k, v in summary.ignored_mismatches.items():
                suite_ignored_mismatches[k] += v
            suite_totals["total_records"] += summary.total_records
            suite_totals["total_player_frames"] += summary.total_player_frames
            suite_totals["total_state_flags"] += summary.total_state_flags
            suite_totals["total_item_slots"] += summary.total_item_slots
            suite_totals["float_norm_sum"] += summary.float_norm_sum
            suite_totals["float_norm_count"] += summary.float_norm_count

        if suite_mismatches is None or suite_strict_mismatches is None or suite_ignored_mismatches is None:
            return

        reporter.print()
        reporter.print("== suite summary ==")
        suite_summary = EvalSummary(
            total_records=suite_totals["total_records"],
            total_player_frames=suite_totals["total_player_frames"],
            total_state_flags=suite_totals["total_state_flags"],
            total_item_slots=suite_totals["total_item_slots"],
            mismatches=suite_mismatches,
            strict_mismatches=suite_strict_mismatches,
            ignored_mismatches=suite_ignored_mismatches,
            profile_name=validation_profile.name,
            float_norm_sum=float(suite_totals["float_norm_sum"]),
            float_norm_count=int(suite_totals["float_norm_count"]),
        )
        mismatches_total, checks_total = _discrete_mismatch_total(suite_summary, profile=validation_profile)
        strict_total, strict_checks = _strict_discrete_mismatch_total(suite_summary)
        reporter.print(f"overall.discrete_mismatch: {mismatches_total} / {checks_total}")
        reporter.print(f"overall.strict_discrete_mismatch: {strict_total} / {strict_checks}")
        reporter.print(f"overall.ignored_discrete_mismatch: {sum(suite_ignored_mismatches.values())}")
        overall_float = (
            suite_summary.float_norm_sum / suite_summary.float_norm_count
            if suite_summary.float_norm_count > 0
            else 0.0
        )
        reporter.print(f"overall.float_norm_mae_p95: {overall_float:.8f}")
    finally:
        reporter.close()


if __name__ == "__main__":
    main()
