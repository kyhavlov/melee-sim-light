from __future__ import annotations

import argparse
import json
from pathlib import Path

from tools.eval.rollout_metrics import summarize_rollout_payload
from tools.eval.run_longest_rollout_streaks import (
    _parse_csv,
    _parse_players,
    _scan_dataset_streaks,
    _validate_discrete_fields,
)
from tools.eval.run_one_step_eval import Reporter
from tools.eval.dataset import read_dataset
from tools.slippi.suite_io import dataset_path_for_suite_replay, load_suite, repo_root


def _preprocess_stamp_lines(*, root: Path, suite_name: str, datasets_dir: str) -> list[str]:
    meta_path = (root / datasets_dir / suite_name / ".preprocess_meta.json").resolve()
    if not meta_path.exists():
        return [
            "# preprocess_suite stamp: missing",
            f"#   expected: {meta_path.relative_to(root)}",
        ]
    try:
        meta = json.loads(meta_path.read_text())
    except Exception as e:  # noqa: BLE001 - report header only
        return [
            "# preprocess_suite stamp: unreadable",
            f"#   path: {meta_path.relative_to(root)}",
            f"#   error: {type(e).__name__}: {e}",
        ]

    force_used = meta.get("force_used", "?")
    built = meta.get("built", "?")
    skipped = meta.get("skipped", "?")
    seed_sz = meta.get("seed_dtype_itemsize", "?")
    sample_sz = meta.get("sample_dtype_itemsize", "?")
    return [
        "# preprocess_suite stamp:",
        f"#   path: {meta_path.relative_to(root)}",
        f"#   force_used: {force_used}  built: {built}  skipped: {skipped}",
        f"#   seed_dtype_itemsize: {seed_sz}  sample_dtype_itemsize: {sample_sz}",
    ]


def _report_header(*, root: Path, suite: str, suite_name: str, datasets_dir: str) -> list[str]:
    return [
        "# NOTE: This report is generated by `make validate-rollout OUT=reports/validation/rollout_suite_eval.txt` and is overwritten on each run.",
        "#",
        "# Dataset cache note:",
        "# - If you see a `record_size mismatch` error, the dataset schema changed and your cached datasets are stale.",
        "#   Refresh cached datasets:",
        f"#     uv run python -m tools.slippi.preprocess_suite --suite {suite} --datasets-dir {datasets_dir}",
        "#",
        *_preprocess_stamp_lines(root=root, suite_name=suite_name, datasets_dir=datasets_dir),
        "#",
        "# Regenerate gitignored ISO-derived data artifacts (if missing/stale):",
        "# - Opcode-25 airborne-state timelines (data/airborne_state_events/{fox,falco}.bin):",
        "#     uv run python -m tools.extraction.extract_fighter_airborne_state_events --iso_dir _iso --melee_decomp refs/melee --special_msids_dir data/special_msids --out_dir data/airborne_state_events --chars fox,falco",
        "# - Opcode-52 x221C_u16_y timelines (data/state_flags_221c_y/{fox,falco}.bin):",
        "#     uv run python -m tools.extraction.extract_fighter_state_flags_221c_y --iso_dir _iso --melee_decomp refs/melee --special_msids_dir data/special_msids --out_dir data/state_flags_221c_y --chars fox,falco",
        "#",
        "# Machine-readable rollout JSON (gitignored triage artifact):",
        "# - Capture current:",
        "#     make rollout-capture ROLLOUT_JSON=reports/triage/current_rollout_streaks.json",
        "# - Summarize current:",
        "#     make rollout-summary ROLLOUT_JSON=reports/triage/current_rollout_streaks.json",
        "# - Diff baseline vs current:",
        "#     make rollout-diff ROLLOUT_BEFORE=reports/triage/rollout_streaks.json ROLLOUT_AFTER=reports/triage/current_rollout_streaks.json",
    ]


def main() -> None:
    ap = argparse.ArgumentParser(description="Rollout suite evaluator (generator-owned text report).")
    ap.add_argument("--suite", required=True, help="Path to suite JSON (e.g. replays/suites/...)")
    ap.add_argument(
        "--datasets-dir",
        default="datasets",
        help="Directory under repo root that stores preprocessed datasets",
    )
    ap.add_argument(
        "--fields",
        default="action_id,animation_index,on_ground,hitlag,hitstun,state_flags",
        help="Comma-separated discrete compare fields.",
    )
    ap.add_argument(
        "--players",
        default=None,
        help="Comma-separated player indices to compare (default: all players in dataset).",
    )
    ap.add_argument("--max-records", type=int, default=0, help="Optional cap (0 = no cap).")
    ap.add_argument("--out", type=Path, default=None, help="optional output path to write the report")
    args = ap.parse_args()

    root = repo_root()
    suite_path = (root / args.suite).resolve()
    suite = load_suite(suite_path)

    fields = _validate_discrete_fields(_parse_csv(str(args.fields)))

    missing = []
    dataset_paths: list[Path] = []
    for entry in suite.replays:
        ds_path = dataset_path_for_suite_replay(
            suite_name=suite.name,
            replay_rel_path=entry.replay,
            datasets_dir=args.datasets_dir,
        )
        if not ds_path.exists():
            missing.append(str(ds_path.relative_to(root)))
        else:
            dataset_paths.append(ds_path)

    if missing:
        print(f"Missing {len(missing)} preprocessed dataset files for suite {suite.name}:")
        for p in missing:
            print(f"  {p}")
        print("Run preprocessing first:")
        print(f"  uv run python -m tools.slippi.preprocess_suite --suite {args.suite} --datasets-dir {args.datasets_dir}")
        raise SystemExit(2)

    per_dataset_payload = []
    for ds_path in dataset_paths:
        ds = read_dataset(str(ds_path))
        num_players = int(ds.header["num_players"])
        players = _parse_players(args.players, num_players=num_players)
        s = _scan_dataset_streaks(
            dataset_path=ds_path,
            ds=ds,
            fields=fields,
            players=players,
            max_records=int(args.max_records),
            ucf_enabled=suite.ucf_enabled,
            ucf_cardinals_1_0_enabled=suite.ucf_cardinals_1_0_enabled,
        )
        per_dataset_payload.append(
            {
                "dataset": str(Path(s.dataset).resolve().relative_to(root)),
                "num_records": s.num_records,
                "max_records_used": s.max_records_used,
                "players": list(s.players),
                "best_len": s.best_len,
                "best_start_record": s.best_start_record,
                "best_end_record_excl": s.best_end_record_excl,
                "best_start_seed_frame_id": s.best_start_seed_frame_id,
                "best_end_ref_frame_id_inclusive": s.best_end_ref_frame_id_inclusive,
                "streak_histogram": s.streak_histogram,
                "first_mismatch_field_counts": s.first_mismatch_field_counts,
                "first_mismatch_field_counts_seeded": s.first_mismatch_field_counts_seeded,
            }
        )

    payload = {
        "suite": suite.name,
        "suite_path": str(Path(args.suite)),
        "datasets_dir": str(args.datasets_dir),
        "ucf_enabled": bool(suite.ucf_enabled),
        "ucf_cardinals_1_0_enabled": bool(suite.ucf_cardinals_1_0_enabled),
        "fields": list(fields),
        "players_csv": None if args.players is None else str(args.players),
        "max_records": int(args.max_records),
        "per_dataset": per_dataset_payload,
    }
    summary = summarize_rollout_payload(payload)
    suite_summary = summary["suite_summary"]

    reporter = Reporter(args.out)
    try:
        if args.out is not None:
            for line in _report_header(
                root=root, suite=args.suite, suite_name=suite.name, datasets_dir=args.datasets_dir
            ):
                reporter.print(line)
            reporter.print()

        reporter.print(
            f"suite: {suite.name}  datasets: {len(dataset_paths)}  "
            f"ucf_enabled: {suite.ucf_enabled}  ucf_cardinals_1_0_enabled: {suite.ucf_cardinals_1_0_enabled}"
        )
        reporter.print(f"fields: {','.join(str(x) for x in summary['fields'])}")

        for row in summary["dataset_summaries"]:
            reporter.print()
            reporter.print(f"== {row['dataset']} ==")
            reporter.print(f"rollout.best_len: {row['best_len']}")
            reporter.print(f"rollout.streak_count: {row['total_streaks']}")
            reporter.print(f"rollout.streak_len.median: {row['median_streak_len']}")
            reporter.print(f"rollout.streak_len.p90: {row['p90_streak_len']}")
            reporter.print(f"rollout.streak_len.p95: {row['p95_streak_len']}")
            reporter.print(f"rollout.streak_len.max: {row['max_streak_len']}")
            reporter.print(f"rollout.first_mismatch_total: {row['first_mismatch_total']}")
            reporter.print(f"rollout.first_mismatch_seeded_total: {row['first_mismatch_seeded_total']}")

        reporter.print()
        reporter.print("== suite summary ==")
        reporter.print(f"overall.rollout.streak_count: {suite_summary['total_streaks']}")
        reporter.print(f"overall.rollout.streak_len.median: {suite_summary['median_streak_len']}")
        reporter.print(f"overall.rollout.streak_len.p90: {suite_summary['p90_streak_len']}")
        reporter.print(f"overall.rollout.streak_len.p95: {suite_summary['p95_streak_len']}")
        reporter.print(f"overall.rollout.streak_len.max: {suite_summary['max_streak_len']}")
        reporter.print(f"overall.rollout.best_len.max: {suite_summary['max_best_len']}")
        reporter.print(f"overall.rollout.first_mismatch_total: {suite_summary['first_mismatch_total']}")
        reporter.print(
            f"overall.rollout.first_mismatch_seeded_total: {suite_summary['first_mismatch_seeded_total']}"
        )
    finally:
        reporter.close()


if __name__ == "__main__":
    main()
