"""Generate abort stubs for decomp symbols the PE link cannot drop.

PE has no symbol visibility, so mingw auto-exports every symbol, every section
is rooted, and --gc-sections cannot discard the unreachable upstream branches
the ELF link does. Their calls into non-imported decomp symbols stay live and
each one needs a definition. Reaching one in a real match aborts with its name,
the same contract as src/stubs/unresolved_abort.c.

Driven by tools/build/build_windows.sh, which feeds it the link's own
undefined-symbol list.
"""

import sys

HEADER = '''/* Generated by tools/build/generate_win_stubs.py. Do not edit. */
#include <stdio.h>
#include <stdlib.h>

static void unexpected(const char* symbol)
{
    fprintf(stderr, "unexpected core dependency: %s\\n", symbol);
    abort();
}

'''


def main() -> None:
    names = [line.strip() for line in open(sys.argv[1]) if line.strip()]
    with open(sys.argv[2], "w") as out:
        out.write(HEADER)
        for name in names:
            out.write('void %s(void) { unexpected("%s"); }\n' % (name, name))
    print("%d stubs" % len(names))


if __name__ == "__main__":
    main()
