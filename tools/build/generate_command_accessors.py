#!/usr/bin/env python3
"""Generate wasm-safe accessors for PPC-authored command bitfields.

GCC's scalar_storage_order pragma gives the native hosted build source-order
bitfield views over authored big-endian command bytes. Clang/wasm32 does not
implement that pragma. Derive named accessors from the same PPC DWARF instead
of duplicating bit positions in gameplay code.

Source owners:
  refs/melee/src/melee/lb/types.h::CmdUnion
  refs/melee/src/melee/lb/types.h::ColorOverlay_x8_t
  refs/melee/src/melee/{ft/ftaction.c,it/itanimlist.c,lb/lbcommand.c,lb/lbspdisplay.c}
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Resolve the sibling module from this checkout even when an installed
# melee_sim distribution also exposes a tools.build package.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.build.generate_native_dat_layout import Dwarf, _WRAPPERS  # noqa: E402


def unwrap(dwarf: Dwarf, die):
    while die is not None and die.tag in _WRAPPERS:
        die = dwarf.ref(die)
    return die


def bit_offset(dwarf: Dwarf, member) -> int:
    if "DW_AT_data_bit_offset" in member.attrs:
        return dwarf.integer(member, "DW_AT_data_bit_offset")
    byte_offset = dwarf.integer(member, "DW_AT_data_member_location", 0)
    storage_bits = dwarf.integer(member, "DW_AT_byte_size") * 8
    return byte_offset * 8 + dwarf.integer(member, "DW_AT_bit_offset", 0)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ppc", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    dwarf = Dwarf.from_layout(args.ppc)
    lines = [
        "// Generated by tools/build/generate_command_accessors.py.",
        "// Do not edit; offsets and signedness come from PPC union DWARF.",
        "#ifndef MSL_CORE_GENERATED_COMMAND_FIELDS_H",
        "#define MSL_CORE_GENERATED_COMMAND_FIELDS_H",
        "",
        "#include <stdint.h>",
        "",
        "static inline __attribute__((always_inline)) uint32_t",
        "msl_cmd_bits(const void* command, uint32_t first, uint32_t width)",
        "{",
        "    const uint8_t* bytes = command;",
        "    uint32_t value = 0;",
        "    uint32_t bit;",
        "    for (bit = 0; bit < width; ++bit) {",
        "        uint32_t source = first + bit;",
        "        value = (value << 1) |",
        "                ((bytes[source / 8] >> (7 - source % 8)) & 1U);",
        "    }",
        "    return value;",
        "}",
        "",
        "static inline __attribute__((always_inline)) int32_t",
        "msl_cmd_signed_bits(const void* command, uint32_t first,",
        "                    uint32_t width)",
        "{",
        "    uint32_t value = msl_cmd_bits(command, first, width);",
        "    if (width != 0 && width < 32 && (value & (1U << (width - 1)))) {",
        "        value |= UINT32_MAX << width;",
        "    }",
        "    return (int32_t) value;",
        "}",
        "",
    ]
    emitted: set[str] = set()
    for union_name, prefix in (
        ("CmdUnion", "msl_cmd"),
        ("ColorOverlay_x8_t", "msl_color"),
    ):
        command_union = unwrap(dwarf, dwarf.named(union_name))
        for union_member in command_union.children:
            if union_member.tag != "DW_TAG_member":
                continue
            owner_name = dwarf.name(union_member)
            owner = unwrap(dwarf, dwarf.ref(union_member))
            if owner is None or owner.tag != "DW_TAG_structure_type":
                continue
            for member in owner.children:
                if member.tag != "DW_TAG_member":
                    continue
                field_name = dwarf.name(member)
                function = f"{prefix}_{owner_name}_{field_name}"
                if function in emitted:
                    continue
                field_type = unwrap(dwarf, dwarf.ref(member))
                if field_type is None:
                    continue
                width = dwarf.integer(member, "DW_AT_bit_size", 0)
                encoding = dwarf.integer(field_type, "DW_AT_encoding", 0)
                signed = encoding in {5, 6}
                if width:
                    first = bit_offset(dwarf, member)
                elif field_type.tag in {
                    "DW_TAG_base_type",
                    "DW_TAG_enumeration_type",
                }:
                    first = (
                        dwarf.integer(member, "DW_AT_data_member_location", 0) * 8
                    )
                    width = dwarf.integer(field_type, "DW_AT_byte_size") * 8
                else:
                    continue
                if width > 32:
                    continue
                return_type = "int32_t" if signed else "uint32_t"
                helper = "msl_cmd_signed_bits" if signed else "msl_cmd_bits"
                lines.extend(
                    [
                        f"static inline __attribute__((always_inline)) {return_type}",
                        f"{function}(const void* command)",
                        "{",
                        f"    return {helper}(command, {first}U, {width}U);",
                        "}",
                        "",
                    ]
                )
                emitted.add(function)
    lines.extend(["#endif", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
